"""
# ShiftGuard-X NB117 — IEEE-754 Evaluation-Path Feasibility Gate

**Novelty is NOT established.** This notebook falsifies a narrow hypothesis: whether a bit-exact choice between `(a+b)+c` and `a+(b+c)` can outperform fully specified baseline encodings on **real derived columns**, with all container bytes included.

**No file uploads or dataset downloads.** A small UCI Bike Sharing subset, preserved as binary64 words from NB116, is embedded in this notebook with a SHA-256 verification. The synthetic workload **deliberately** matches the candidate construction and **must not** be used to claim general performance.

It compares (1) whole-file Zstandard, (2) raw target with separately compressed side columns, (3) bitwise XOR with one decoder-derived prediction, and (4) dual-path candidate choice plus exact raw-word escapes. The decoder has no access to the original target except stored payload.

The codec depends on explicit binary64 intermediate rounding on the executing machine. A production/portable format would need a normative arithmetic reference implementation and rounding semantics (not `fast-math`). Prior work on multiple predictive codecs and cross-column correlation overlaps substantially. **This test is not a systematic proof of novelty.**
"""

