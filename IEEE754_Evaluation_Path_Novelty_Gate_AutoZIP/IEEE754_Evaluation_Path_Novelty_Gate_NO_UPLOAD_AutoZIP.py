MAGIC=b'SGXPATH2'
def bitwords(x):
 a=np.ascontiguousarray(x,dtype='<f8')
 assert a.ndim==1
 return a.view('<u8')
def derive(a,b,c):
 a,b,c=[np.ascontiguousarray(x,dtype='<f8') for x in (a,b,c)]
 with np.errstate(over='ignore',under='ignore',invalid='ignore'):
  p0=np.add(np.add(a,b),c)
  p1=np.add(a,np.add(b,c))
 return bitwords(p0),bitwords(p1)
def pack_file(mode,a,b,c,y):
 a,b,c,y=[np.ascontiguousarray(x,dtype='<f8') for x in (a,b,c,y)]
 n=len(y);assert len(a)==len(b)==len(c)==n
 if mode=='whole':
  parts=[ZC.compress(np.stack([a,b,c,y]).astype('<f8').tobytes())]
 else:
  parts=[ZC.compress(np.stack([a,b,c]).astype('<f8').tobytes())]
  target=bitwords(y);p0,p1=derive(a,b,c)
  if mode=='raw':
   parts.append(ZC.compress(target.tobytes()))
  elif mode=='xor':
   parts.append(ZC.compress(np.bitwise_xor(target,p0).tobytes()))
  elif mode=='dual':
   ix=np.full(n,2,dtype=np.uint8)
   ix[target==p1]=1
   ix[target==p0]=0
   parts.extend([ZC.compress(ix.tobytes()),ZC.compress(target[ix==2].tobytes())])
  else:raise ValueError(mode)
 header={'format':'SGX117-DIAGNOSTIC','n':n,'method':mode,'part_sizes':[len(x) for x in parts],
         'columns':['source_a','source_b','source_c','target_y'],'dtype':'ieee754-float64-little-endian',
         'rounding':'IEEE binary64 intermediates, local numpy; nonportable without reference'}
 blob=json.dumps(header,sort_keys=True,separators=(',',':')).encode()
 return MAGIC+struct.pack('<I',len(blob))+blob+b''.join(parts)
def unpack_file(blob):
 assert blob[:8]==MAGIC
 m=struct.unpack_from('<I',blob,8)[0];hdr=json.loads(blob[12:12+m]);pay=blob[12+m:]
 sizes=hdr['part_sizes'];assert len(pay)==sum(sizes)
 parts=[];offset=0
 for length in sizes:
  parts.append(pay[offset:offset+length]);offset+=length
 n=hdr['n'];mode=hdr['method']
 if mode=='whole':
  raw=ZD.decompress(parts[0]);assert len(raw)==32*n
  return np.frombuffer(raw,dtype='<u8').reshape(4,n).copy()
 side=ZD.decompress(parts[0]);assert len(side)==24*n
 xyz=np.frombuffer(side,dtype='<u8').reshape(3,n).copy()
 a,b,c=xyz.view('<f8')
 p0,p1=derive(a,b,c)
 if mode=='raw':
  raw=ZD.decompress(parts[1]);assert len(raw)==8*n
  y=np.frombuffer(raw,dtype='<u8').copy()
 elif mode=='xor':
  raw=ZD.decompress(parts[1]);assert len(raw)==8*n
  y=np.bitwise_xor(np.frombuffer(raw,dtype='<u8'),p0)
 elif mode=='dual':
  ix=np.frombuffer(ZD.decompress(parts[1]),dtype=np.uint8)
  assert len(ix)==n and np.all(ix<=2)
  fallback=np.frombuffer(ZD.decompress(parts[2]),dtype='<u8')
  assert len(fallback)==np.count_nonzero(ix==2)
  y=np.empty(n,dtype='<u8');y[ix==0]=p0[ix==0];y[ix==1]=p1[ix==1];y[ix==2]=fallback
 else:raise ValueError(mode)
 return np.concatenate([xyz,y[None,:]],axis=0)
def evaluate(label,a,b,c,y,source_kind):
 actual=np.stack([bitwords(v) for v in [a,b,c,y]])
 results=[]
 p0,p1=derive(a,b,c);target=bitwords(y)
 for mode in ['whole','raw','xor','dual']:
  encoded=pack_file(mode,a,b,c,y)
  decoded=unpack_file(encoded)
  bit_exact=bool(np.array_equal(actual,decoded))
  assert bit_exact,f'{label} mode={mode} mismatch'
  results.append({'dataset':label,'source_kind':source_kind,'method':mode,'bytes_full_container':len(encoded),
                  'n_rows':len(y),'bit_exact':bit_exact,'path_disagreements':int(np.count_nonzero(p0!=p1)),
                  'p0_exact_matches':int(np.count_nonzero(p0==target)),
                  'p1_extra_exact_matches':int(np.count_nonzero((p1==target)&(p0!=target)))})
 return results
